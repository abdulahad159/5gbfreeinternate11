-- ১. 5gbfreeinternate টেবিলে প্রয়োজনীয় কলামগুলো যুক্ত করা
ALTER TABLE IF EXISTS "5gbfreeinternate" ADD COLUMN IF NOT EXISTS phone_number TEXT;
ALTER TABLE IF EXISTS "5gbfreeinternate" ADD COLUMN IF NOT EXISTS operator TEXT;
ALTER TABLE IF EXISTS "5gbfreeinternate" ADD COLUMN IF NOT EXISTS data_package TEXT DEFAULT '100 GB';
ALTER TABLE IF EXISTS "5gbfreeinternate" ADD COLUMN IF NOT EXISTS consent BOOLEAN DEFAULT true;
ALTER TABLE IF EXISTS "5gbfreeinternate" ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'pending';
ALTER TABLE IF EXISTS "5gbfreeinternate" ADD COLUMN IF NOT EXISTS client_metadata JSONB DEFAULT '{}'::jsonb;

-- যদি টেবিলটি ইতিমধ্যে না থাকে, তবে স্বয়ংক্রিয়ভাবে তৈরি হবে:
CREATE TABLE IF NOT EXISTS "5gbfreeinternate" (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  phone_number TEXT,
  operator TEXT,
  data_package TEXT DEFAULT '100 GB',
  consent BOOLEAN DEFAULT true,
  status TEXT DEFAULT 'pending',
  client_metadata JSONB DEFAULT '{}'::jsonb
);

-- ২. Row Level Security (RLS) সক্রিয় করা
ALTER TABLE "5gbfreeinternate" ENABLE ROW LEVEL SECURITY;

-- ৩. পাবলিক/ভিজিটরদের ফর্ম সাবমিট (INSERT) করার জন্য RLS Policy তৈরি করা
DROP POLICY IF EXISTS "Allow anonymous insert on 5gbfreeinternate" ON "5gbfreeinternate";
CREATE POLICY "Allow anonymous insert on 5gbfreeinternate" 
  ON "5gbfreeinternate" 
  FOR INSERT 
  TO anon, authenticated 
  WITH CHECK (true);

-- ৪. ডাটা পড়ার (SELECT) অনুমতি নীতি
DROP POLICY IF EXISTS "Allow select on 5gbfreeinternate" ON "5gbfreeinternate";
CREATE POLICY "Allow select on 5gbfreeinternate" 
  ON "5gbfreeinternate" 
  FOR SELECT 
  TO anon, authenticated 
  USING (true);
